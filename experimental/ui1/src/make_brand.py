"""Convert the supplied classic vector artwork to Qt paths; no font substitution."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
root = ET.fromstring((HERE / 'assets/jaguar-stacked.svg').read_text())

def path_code(d):
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?', d)
    i = 0; cmd = None; x = y = sx = sy = 0; control = None; lines = []
    arity = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'S': 4}
    def emit(op, vals=()):
        lines.append('p.' + op + '(' + ','.join(f'qreal({v:.6f})' for v in vals) + ');')
    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]; i += 1
        upper = cmd.upper()
        if upper == 'Z':
            emit('closeSubpath'); x, y = sx, sy; control = None; cmd = None; continue
        count = arity[upper]
        a = [float(v) for v in tokens[i:i+count]]; i += count
        relative = cmd.islower()
        if upper in ('M', 'L'):
            nx, ny = a
            if relative: nx += x; ny += y
            emit('moveTo' if upper == 'M' else 'lineTo', (nx, ny))
            x, y = nx, ny
            if upper == 'M': sx, sy = x, y; cmd = 'l' if relative else 'L'
            control = None
        elif upper in ('H', 'V'):
            if upper == 'H': x = a[0] + (x if relative else 0)
            else: y = a[0] + (y if relative else 0)
            emit('lineTo', (x, y)); control = None
        else:
            if upper == 'S':
                first = (2*x-control[0], 2*y-control[1]) if control else (x,y)
                if relative: a = [a[j] + (x if j%2 == 0 else y) for j in range(4)]
                a = list(first) + a
            elif relative:
                a = [a[j] + (x if j%2 == 0 else y) for j in range(6)]
            emit('cubicTo', a); control = tuple(a[2:4]); x,y = a[4:6]
    return '\n'.join(lines)

out = ['// Generated by make_brand.py from assets/jaguar-stacked.svg.',
       '// Jaguar trademark artwork; see assets/branding-source.json.']
paths = [e for e in root if e.attrib.get('fill') != 'none']
for name, parts in [('stacked', paths)]:
    out += ['static QPainterPath jaguar_' + name + '() { QPainterPath p; p.setFillRule(Qt::OddEvenFill);']
    out += [path_code(e.attrib['d']) for e in parts]
    out += ['return p; }']
(HERE/'brand_paths.h').write_text('\n'.join(out)+'\n')
print('Generated the supplied stacked Jaguar logo paths.')
