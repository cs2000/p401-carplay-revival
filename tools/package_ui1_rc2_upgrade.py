#!/usr/bin/env python3
"""Package RC2 for the owner's existing R1 + field-W3 Jaguar installation.

The previous owner-tested installer is the exact restore payload. This is a
UI-only autocopy upgrade, not a full firmware image or an unbootable-unit rescue.
Complete fresh native evidence for the supplied ARM binary is required.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import struct
import subprocess
import tempfile

from package_ui1_candidate import (
    ARCHIVED_ROLLBACK_SHA256, COMPATIBILITY, INSTALL_PATHS, LIBRARY, PREFIX,
    REPO, RUNNER, STATE, UI, W3_MANIFEST, WRAPPER, archived_packages,
    crc_length, description, package_metadata, read_zip, replace_manifest_row,
    require, row, sha256, source_snapshot, zip_install,
)

PREVIOUS = UI / "candidates/glass-clock-2026-11-06"
PREVIOUS_INSTALL_SHA256 = "3fffedb75dd811ea6a41f0c81f756ced773b41a472420e6ff7f2c038dfead383"
PREVIOUS_LIBRARY_SHA256 = "c62c2d49d3ce423d9cf11d96325e7ee5e50d7967ce0a865b2cf6f3a6f6593639"
LINK_PATH = "usr/lib/libLinkLibs.so"
LINK_SHA256 = "ac7d73df4bdd7dfa59e4042dbf46c19797eb3ce84cca630dff79308911e8acdc"
LINK_ROW = b"59ed7170 129180 /usr/lib/libLinkLibs.so"
MARKER = ".p401-ui1-rc2-upgrade"
OUTPUTS = {"INSTALL.zip", "RESTORE_PREVIOUS_UI.zip", "DISABLE_UI.zip",
           "MANIFEST.json", "NATIVE_EVIDENCE.json", MARKER}


def previous_package() -> tuple[dict[str, bytes], bytes, bytes]:
    """Pin all old payloads; never regenerate the owner's working installer."""
    _, baseline, disable = archived_packages()
    data = (PREVIOUS / "INSTALL.zip").read_bytes()
    require(sha256(data) == PREVIOUS_INSTALL_SHA256, "Owner-tested previous installer changed")
    files = read_zip(data)
    manifest = json.loads((PREVIOUS / "MANIFEST.json").read_text())
    packages = [p for p in manifest["packages"] if p["file"] == "INSTALL.zip"]
    require(len(packages) == 1 and package_metadata("INSTALL.zip", data) == packages[0],
            "Previous package differs from its preserved manifest")
    require(set(files) == {PREFIX + path for path in INSTALL_PATHS}, "Previous installer must contain six files")
    require(sha256(files[PREFIX + LIBRARY]) == PREVIOUS_LIBRARY_SHA256,
            "Previous library is not the exact owner-tested c62 artifact")
    require(files[PREFIX + STATE] == b"enabled\n", "Previous installer must enable the old Jaguar UI")
    require(sha256(disable) == ARCHIVED_ROLLBACK_SHA256, "Historical UI-disable archive changed")
    old_rows = baseline[PREFIX + W3_MANIFEST].splitlines()
    previous_rows = files[PREFIX + W3_MANIFEST].splitlines()
    require(len(old_rows) == len(previous_rows), "Previous W3 manifest row count changed")
    require([(a, b) for a, b in zip(old_rows, previous_rows) if a != b]
            == [(row(baseline[PREFIX + RUNNER], RUNNER), row(files[PREFIX + RUNNER], RUNNER))],
            "Previous W3 manifest changes more than the GUI runner")
    return files, data, disable


def destination_safe(output: Path, replace: bool) -> None:
    require(not output.is_symlink(), "Output may not be a symlink")
    resolved = output.resolve()
    for protected in (UI / "packages", UI / "candidates", REPO / "releases", REPO / "recovery"):
        require(not resolved.is_relative_to(protected.resolve()), "Do not replace archived/public files")
    if output.exists():
        require(replace and output.is_dir(), "Use a new destination or --replace for this tool's output")
        require((output / MARKER).is_file() and (output / MARKER).read_bytes() == b"p401-ui1-rc2-upgrade-v1\n",
                "Refusing to replace an unrelated directory")
        require({p.name for p in output.iterdir()} == OUTPUTS and
                all(p.is_file() and not p.is_symlink() for p in output.iterdir()),
                "Output contains files not generated by this tool")


def build(binary_path: Path, evidence_path: Path, output: Path, replace: bool = False) -> dict:
    previous, previous_zip, disable_zip = previous_package()
    _, baseline, _ = archived_packages()
    binary = binary_path.read_bytes()
    require(len(binary) >= 52 and binary[:7] == b"\x7fELF\x01\x01\x01", "Expected little-endian ELF32")
    require(struct.unpack_from("<HH", binary, 16) == (3, 40), "Expected ARM shared object")
    require(struct.unpack_from("<I", binary, 36)[0] & 0x400 != 0, "Expected ARM hard-float ABI")
    binary_sha = sha256(binary)
    require(binary_sha != PREVIOUS_LIBRARY_SHA256, "RC2 cannot contain the previous RC1 UI binary")
    evidence_bytes = evidence_path.read_bytes()
    evidence = json.loads(evidence_bytes)
    require(evidence.get("passed") is True and evidence.get("complete") is True,
            "Fresh RC2 native evidence must be passed and complete")
    require(evidence.get("library_sha256") == binary_sha, "Native evidence does not match supplied library")
    cases = evidence.get("cases")
    require(isinstance(cases, list) and cases and
            all(isinstance(case, dict) and case.get("passed") is True for case in cases),
            "Fresh native evidence must contain passed cases")
    snapshot = source_snapshot()
    require(evidence.get("source_snapshot") == snapshot,
            "Fresh native evidence source snapshot does not match current UI source")
    destination_safe(output, replace)

    old_compatibility = previous[PREFIX + COMPATIBILITY]
    old_rows = old_compatibility.splitlines()
    require(len(old_rows) == 10 and old_rows[0] == row(previous[PREFIX + LIBRARY], LIBRARY),
            "Previous compatibility must contain the UI and nine original vendor pins")
    require(not any(line.endswith(b"/" + LINK_PATH.encode()) for line in old_rows),
            "Connection ABI pin unexpectedly exists in previous package")
    compatibility = (row(binary, LIBRARY) + b"\n" +
                     b"".join(line + b"\n" for line in old_rows[1:]) + LINK_ROW + b"\n")
    require(compatibility.splitlines()[1:10] == old_rows[1:], "Original vendor ABI pins changed")
    template = (UI / "src/run-ui.sh.in").read_bytes()
    require(template.count(b"@MANIFEST_CHECK@") == 1, "Expected one wrapper manifest placeholder")
    wrapper = template.replace(b"@MANIFEST_CHECK@", crc_length(compatibility).encode())
    old_runner = baseline[PREFIX + RUNNER]
    launch = b"MsnCoreApp -qws 2>&1 | /bin/sh /usr/bin/p401-log-stream.sh core"
    require(old_runner.count(launch) == 1, "Exact baseline launch command missing or ambiguous")
    replacement = (b'if "$helper" verify /data/carplay-revival/run-ui.sh ' + crc_length(wrapper).encode() + b'; then\n'
                   b'    /bin/sh /data/carplay-revival/run-ui.sh 2>&1 | /bin/sh /usr/bin/p401-log-stream.sh core\n'
                   b'else\n    ' + launch + b'\nfi')
    runner = old_runner.replace(launch, replacement)
    old_manifest = previous[PREFIX + W3_MANIFEST]
    manifest = replace_manifest_row(old_manifest, row(previous[PREFIX + RUNNER], RUNNER),
                                    row(runner, RUNNER), "previous UI runner")
    require([(a, b) for a, b in zip(old_manifest.splitlines(), manifest.splitlines()) if a != b]
            == [(row(previous[PREFIX + RUNNER], RUNNER), row(runner, RUNNER))],
            "Only the GUI runner row may change in the working W3 manifest")
    payload = {PREFIX + LIBRARY: binary, PREFIX + COMPATIBILITY: compatibility,
               PREFIX + WRAPPER: wrapper, PREFIX + STATE: b"enabled\n",
               PREFIX + RUNNER: runner, PREFIX + W3_MANIFEST: manifest}
    require(set(payload) == {PREFIX + path for path in INSTALL_PATHS}, "Upgrade must contain exactly six files")
    installer = zip_install(payload)
    report = {
        "revision": "2026.11-jaguar-xfr-rc2-field-upgrade",
        "status": "Fresh native/offline checked UI candidate; RC2 physical vehicle testing pending",
        "requires": "Owner's R1 + field-W3 startup layout with the owner-tested Glass + Clock UI",
        "not_for": "Standalone full Jaguar RC1/RC2 startup layout; use the full firmware bundle there",
        "checkout_head": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO, text=True).strip(),
        "library_sha256": binary_sha,
        "previous_installer_sha256": PREVIOUS_INSTALL_SHA256,
        "previous_library_sha256": PREVIOUS_LIBRARY_SHA256,
        "extra_abi_pin": {"path": LINK_PATH, "crc32": "59ed7170", "bytes": 129180, "sha256": LINK_SHA256},
        "native_evidence": {"file": "NATIVE_EVIDENCE.json", **description(evidence_bytes), "case_count": len(cases)},
        "packager": {"file": Path(__file__).relative_to(REPO).as_posix(), **description(Path(__file__).read_bytes())},
        "source_snapshot": snapshot,
        "packages": [package_metadata("INSTALL.zip", installer),
                     package_metadata("RESTORE_PREVIOUS_UI.zip", previous_zip),
                     package_metadata("DISABLE_UI.zip", disable_zip)],
        "rollback_note": "RESTORE_PREVIOUS_UI.zip is byte-for-byte the owner's previous successful installer: it restores the exact c62 library, ABI manifest, UI wrapper, enabled state, GUI runner and working W3 manifest. DISABLE_UI.zip is the unchanged original three-file UI-off rollback. Neither touches name, appearance, MCU, factory settings, kernel or rootfs.",
        "hardware_radio_tested": False, "physical_reboot_tested": False,
        "kernel_rootfs_changed": False, "w3_fix_bytes_changed": False,
        "factory_mcu_changed": False, "saved_name_appearance_changed": False,
        "flash_backup": False, "full_flash_restore_available": False,
        "warning": "Does not back up firmware. Rollback requires a booting box accepting autocopy; no bricked-unit recovery is offered.",
    }
    contents = {"INSTALL.zip": installer, "RESTORE_PREVIOUS_UI.zip": previous_zip,
                "DISABLE_UI.zip": disable_zip, "NATIVE_EVIDENCE.json": evidence_bytes,
                "MANIFEST.json": (json.dumps(report, indent=2) + "\n").encode(),
                MARKER: b"p401-ui1-rc2-upgrade-v1\n"}
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".ui1-rc2-upgrade-", dir=output.parent) as temporary:
        stage = Path(temporary)
        for name, data in contents.items():
            (stage / name).write_bytes(data)
        output.mkdir(exist_ok=replace)
        for name in sorted(contents):
            os.replace(stage / name, output / name)
    return {"output": str(output), "library_sha256": binary_sha,
            "packages": report["packages"], "physical_vehicle_tested": False}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=UI / "build/libp401-ui.so")
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=UI / "build/cloud/rc2-upgrade")
    parser.add_argument("--replace", action="store_true")
    args = parser.parse_args()
    try:
        result = build(args.binary.resolve(), args.evidence.resolve(), args.output.absolute(), args.replace)
    except (ValueError, OSError, KeyError, json.JSONDecodeError) as error:
        parser.exit(1, f"RC2 upgrade packaging refused: {error}\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
